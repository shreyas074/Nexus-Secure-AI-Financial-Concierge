"""The typed intake schema (spec 3.2). Nothing downstream runs until a request validates against it."""
import uuid
from enum import Enum
from typing import Optional

from pydantic import BaseModel, ConfigDict, Field, ValidationError, field_validator

from errors import IntakeValidationError, InvalidIdFormat
from guardrails import redact_for_logging, validate_id
from logging_config import get_logger, trace

logger = get_logger("schemas")


class ProductLine(str, Enum):
    banking = "banking"
    insurance = "insurance"
    wealth = "wealth"
    cross_product = "cross_product"


class RequestType(str, Enum):
    balance_inquiry = "balance_inquiry"
    coverage_question = "coverage_question"
    auto_debit_setup = "auto_debit_setup"
    portfolio_query = "portfolio_query"
    claim_status = "claim_status"
    complaint = "complaint"
    other = "other"


class Urgency(str, Enum):
    routine = "routine"
    high = "high"
    critical = "critical"


class EscalationCategory(str, Enum):
    none = "none"
    financial_hardship = "financial_hardship"
    safeguarding_concern = "safeguarding_concern"
    compliance_override_request = "compliance_override_request"


def new_request_id():
    return "REQ-" + uuid.uuid4().hex[:10].upper()


_OPTIONAL_IDS = {"account_id": "account", "policy_id": "policy", "portfolio_id": "portfolio",
                 "claim_id": "claim", "product_id": "product"}


def _checked_id(kind, value):
    """validate_id raises our typed error; pydantic validators must raise ValueError to be reported per field."""
    try:
        return validate_id(kind, value)
    except InvalidIdFormat as exc:
        raise ValueError(exc.message) from exc


class IntakeRequest(BaseModel):
    model_config = ConfigDict(extra="forbid")  # unknown fields are an error, never silently dropped

    request_id: str                       # server-generated (see build_intake), never caller-supplied
    customer_id: str
    product_line: ProductLine
    request_type: RequestType
    urgency: Urgency
    customer_stated_intent: str           # already sanitised by guardrails.sanitize_free_text
    escalation_category: EscalationCategory = EscalationCategory.none
    # Optional product references (from the message or the authenticated app session)
    account_id: Optional[str] = None
    policy_id: Optional[str] = None
    portfolio_id: Optional[str] = None
    claim_id: Optional[str] = None
    product_id: Optional[str] = None

    @field_validator("customer_id")
    @classmethod
    def _customer_format(cls, value):
        return _checked_id("customer", value)

    @field_validator("customer_stated_intent")
    @classmethod
    def _intent_not_empty(cls, value):
        if not value.strip():
            raise ValueError("customer_stated_intent must not be empty")
        return value

    @field_validator("account_id", "policy_id", "portfolio_id", "claim_id", "product_id")
    @classmethod
    def _optional_id_format(cls, value, info):
        return value if value is None else _checked_id(_OPTIONAL_IDS[info.field_name], value)


@trace(logger, redact=redact_for_logging)
def build_intake(raw, request_id):
    """Validate a raw dict into an IntakeRequest or raise ONE typed IntakeValidationError.

    request_id is always generated by the server: if a caller supplies one it is discarded.
    """
    data = {k: v for k, v in raw.items() if k != "request_id"}
    try:
        return IntakeRequest(request_id=request_id, **data)
    except ValidationError as exc:
        problems = [{"field": ".".join(str(p) for p in e["loc"]), "problem": e["msg"]} for e in exc.errors()]
        raise IntakeValidationError("Intake validation failed", problems=problems) from exc
